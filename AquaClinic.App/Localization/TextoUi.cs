    public static string T(string? texto)
    {
        if (string.IsNullOrEmpty(texto))
        {
            return string.Empty;
        }

        var lineas = texto.Split(["\r\n", "\n"], StringSplitOptions.None);
        return string.Join(Environment.NewLine, lineas.Select(TraducirLinea));
    }

    private static string TraducirLinea(string texto)
    {
        if (CultureInfo.CurrentUICulture.Name.StartsWith("es", StringComparison.OrdinalIgnoreCase))
        {
            return texto;
        }

        return Traducciones.TryGetValue(texto, out var traduccion) ? traduccion : texto;
    }
